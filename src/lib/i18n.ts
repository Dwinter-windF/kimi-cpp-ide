const DICTS: Record<LanguageId, Dict> = { "zh-CN": zh, "en-US": en };

/** 已警告过的缺失 key（每个 key 只 warn 一次，避免刷屏） */
const warnedKeys = new Set<string>();

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : m
  );
}

function warnMissing(key: string): void {
  if (warnedKeys.has(key)) return;
  warnedKeys.add(key);
  console.warn(`[i18n] missing translation key: ${key}`);
}

/** 按指定语言翻译（找不到时回退中文；两套都没有则返回 key 并 warn 一次） */
export function translate(lang: LanguageId, key: string, vars?: Record<string, string | number>): string {
  const current = DICTS[lang] ?? zh;
  let raw = current[key];
  if (raw === undefined) {
    if (lang !== "zh-CN") warnMissing(key);
    raw = zh[key];
  }
  if (raw === undefined) {
    warnMissing(key);
    return key;
  }
  return interpolate(raw, vars);
}

/** 非组件环境（store / lib）用的即时翻译：每次调用读取当前 store 里的语言 */
export function t(key: string, vars?: Record<string, string | number>): string {
  return translate(languageOf(useIde.getState().settings), key, vars);
}

/**
 * 组件用翻译 Hook：订阅 store.settings.language，
 * 语言切换时组件随 store 自动重渲染，无需刷新页面。
 */
export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const lang = useIde((s) => languageOf(s.settings));
  return useCallback(
    (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars),
    [lang]
  );
}

/** 供测试 / 诊断：两套字典的 key 总数 */
export function dictionarySizes(): { zh: number; en: number } {
  return { zh: Object.keys(zh).length, en: Object.keys(en).length };
}
